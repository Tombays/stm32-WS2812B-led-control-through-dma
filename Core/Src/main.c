void WS2812_SetPixel(uint16_t index, uint8_t r, uint8_t g, uint8_t b){
	led_data[index][0] = g;
	led_data[index][1] = r;
	led_data[index][2] = b;
}

void WS2812_Show(){
	// Reset the blocking flag
	_dma_done = 0;

	// Encode led_data[] into pwm_buffer[]
	uint16_t pwm_index = 0;

	// We will be beginning each packet with 0 due to some bug in DMA that doubles the length of the first bit
	pwm_buffer[pwm_index++] = 0;
	for (int index = 0; index < NUM_LEDS; index++){
		for(int colorIndex = 0; colorIndex < 3; colorIndex++){
			for(int bitIndex = 0; bitIndex < 8; bitIndex++){
				if (led_data[index][colorIndex] & (0x80 >> bitIndex)){
					pwm_buffer[pwm_index++] = 80;
				} else {
					pwm_buffer[pwm_index++] = 40;
				}
			}
		}
	}

	//Append reset zeroes
	for (int index = 0; index < WS2812_RESET_BITS; index++){
		pwm_buffer[pwm_index++] = 0;
	}

	// Start TIM1 DMA
	HAL_TIM_PWM_Start_DMA(&htim1, TIM_CHANNEL_1, (uint32_t *)pwm_buffer, NUM_LEDS * 24 + WS2812_RESET_BITS);

	// Wait until it ends to not mess up things.
	while (!_dma_done){}
}

void HAL_TIM_PWM_PulseFinishedCallback(TIM_HandleTypeDef *htim){
	if (htim->Instance == TIM1){
		_dma_done = 1;
	}
}

